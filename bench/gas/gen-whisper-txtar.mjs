// generates a gno.land integration testscript that measures the gas of one Whisper SendMessage
// as the realm's history grows. It embeds the packages exactly as they are in the given trees (tests excluded), loads
// them at genesis, registers two identities, subscribes the sender to Pro (2,500 credits) and sends N messages, one
// transaction each. Every send's "GAS USED" lands in the script log; the script ends on a deliberate non-match, so
// testscript prints that log for gas-curve.mjs to read.
// Usage: node gen-whisper-txtar.mjs <sdk repo> <whisper repo> <sends> <label> <out.txtar>
import fs from 'node:fs';
import path from 'node:path';

const [sdk, wh, sendsArg, label, out] = process.argv.slice(2);
const sends = Number(sendsArg);
if (!sdk || !wh || !Number.isInteger(sends) || sends < 1 || !label || !out) {
  throw new Error('usage: gen-whisper-txtar.mjs <sdk repo> <whisper repo> <sends> <label> <out.txtar>');
}
const pkgs = [
  ['gno.land/p/arobi/signals', path.join(sdk, 'gno.land/p/arobi/signals'), 'signals'],
  ['gno.land/p/arobi/assurance', path.join(sdk, 'gno.land/p/arobi/assurance'), 'passurance'],
  ['gno.land/p/arobi/whisper', path.join(wh, 'gno.land/p/arobi/whisper'), 'pwhisper'],
  ['gno.land/r/arobi/whisper', path.join(wh, 'gno.land/r/arobi/whisper'), 'rwhisper'],
];
const ENC_A = '1'.repeat(64), ENC_B = '2'.repeat(64), EPH = 'a'.repeat(64), NONCE = 'b'.repeat(48), COMMIT = 'c'.repeat(64);
const CT = Buffer.from('sealed-xchacha20-poly1305-ciphertext-payload').toString('base64');
const call = (func, args, key, send = '') =>
  `gnokey maketx call -pkgpath gno.land/r/arobi/whisper -func ${func}${args.map((a) => ` -args '${a}'`).join('')}` +
  `${send ? ` -send ${send}` : ''} -gas-fee 90000001ugnot -gas-wanted 900000000 -chainid=tendermint_test ${key}\nstdout 'OK!'\n`;

let s = `# Whisper SendMessage gas as history grows (${label}): ${sends} sends, one transaction each. Generated by gen-whisper-txtar.mjs.\n\n`;
s += 'loadpkg gno.land/p/nt/avl/v0\n';
for (const [p, , dir] of pkgs) s += `loadpkg ${p} $WORK/${dir}\n`;
s += '\nadduser bob\n\ngnoland start\n\n';
s += call('RegisterIdentity', [ENC_A, '', 'alice_gas', 'Alice'], 'test1');
s += call('RegisterIdentity', [ENC_B, '', 'bob_gas', 'Bob'], 'bob');
s += call('Subscribe', [], 'test1', '25000000ugnot');
for (let i = 1; i <= sends; i++) {
  s += `# send ${i}\n` + call('SendMessage', ['@bob_gas', EPH, NONCE, CT, COMMIT], 'test1');
}
s += "\n# The end: a deliberate non-match, so testscript prints the whole log (every GAS USED) for gas-curve.mjs.\nstdout 'GAS_HARNESS_DUMP_SENTINEL'\n\n";
for (const [, dir, name] of pkgs) {
  for (const f of fs.readdirSync(dir).sort()) {
    if (!(f.endsWith('.gno') || f === 'gnomod.toml') || f.endsWith('_test.gno') || f.endsWith('_filetest.gno')) continue;
    s += `-- ${name}/${f} --\n${fs.readFileSync(path.join(dir, f), 'utf8').replace(/\r\n/g, '\n')}\n`;
  }
}
fs.writeFileSync(out, s);
console.log(`${out}: ${sends} sends, ${(s.length / 1024).toFixed(0)} KB`);
